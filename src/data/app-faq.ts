export function getAppFaq(slug: string) {
  return appFaqs.find((item) => item.slug === slug);
}

export function relatedFaqs(item: AppFaq) {
  return item.related
    .map((slug) => getAppFaq(slug))
    .filter((faq): faq is AppFaq => Boolean(faq));
}

export function getTopic(slug: string) {
  return topics.find((t) => t.slug === slug);
}

function wonIn(text: string) {
  const eok = text.match(/(\d+(?:\.\d+)?)\s*억/);
  const man = text.match(/(\d+(?:\.\d+)?)\s*만/);
  const eokN = eok ? Number(eok[1]) * 10000 : 0;
  const manN = man ? Number(man[1]) : 0;
  return Math.max(eokN, manN);
}

/** 태그색: 10만 이하 / 50만 이하 / 100만 이하 / 100만 초과 / 1000만 초과 / 없음 */
export function fineTone(label: string) {
  if (/없음/.test(label)) return "none";
  const n = wonIn(label);
  if (!n) return "open";
  if (n > 1000) return "mega";
  if (n <= 10) return "t10";
  if (n <= 50) return "t50";
  if (n <= 100) return "t100";
  return "high";
}

/** 💰 10만 미만 1개 · 100만 미만 2개 · 그 이상 3개 */
export function fineBagCount(label: string) {
  if (/없음/.test(label)) return 0;
  const n = wonIn(label);
  if (!n) return 0;
  if (n < 10) return 1;
  if (n < 100) return 2;
  return 3;
}

export function rowAmount(a: Amount) {
  const n = Math.max(wonIn(a.car), wonIn(a.van ?? ""));
  return n ? `${n}만 원` : a.car;
}

export function maxFineLabel(topic: Topic) {
  if (topic.slug === "bounty") return topic.penaltyLead;
  let max = 0;
  for (const a of topic.amounts) {
    max = Math.max(max, wonIn(a.car), wonIn(a.van ?? ""));
  }
  max = Math.max(max, wonIn(topic.penaltyLead));
  return max ? `최대 ${max}만 원` : topic.penaltyLead;
}
